#!/usr/bin/env python
"""
Per-instance evaluation metrics for SWE-Master runs.

Reads one or more R2E-Gym trajectory jsonl files, and for every instance extracts
token usage, step count, timing, and outcome. Writes a per-instance CSV and prints
an aggregate summary.

Usage:
  python scripts/metrics.py <run.jsonl> [<run2.jsonl> ...] [--csv out.csv]
  python scripts/metrics.py            # defaults to results/runA + results/runB
"""
import json
import os
import sys
import csv
import statistics as st


def per_instance(t):
    ds = t.get("ds") or {}
    steps = t.get("trajectory_steps") or []
    # completion tokens summed = total tokens the model generated over the trajectory.
    # prompt tokens summed = total prefill work. peak_context = largest single call.
    comp = sum(s.get("token_usage_completion", 0) or 0 for s in steps)
    prompt = sum(s.get("token_usage_prompt", 0) or 0 for s in steps)
    peak_ctx = max((s.get("token_usage_total", 0) or 0 for s in steps), default=0)
    llm_t = sum(s.get("llm_exec_time", 0) or 0 for s in steps)
    env_t = sum(s.get("env_exec_time", 0) or 0 for s in steps)
    traj_t = max((s.get("total_time_traj", 0) or 0 for s in steps), default=0)
    return {
        "instance_id": ds.get("instance_id", t.get("instance_id", "?")),
        "repo": ds.get("repo", "?"),
        "resolved": int((t.get("reward") or 0) >= 1),
        "exit_reason": t.get("exit_reason", "?"),
        "num_steps": len(steps),
        "completion_tokens": comp,      # total generated by the model
        "prompt_tokens": prompt,        # total prefill (sum over calls; grows each step)
        "peak_context_tokens": peak_ctx,  # largest prompt+gen in a single call
        "llm_time_s": round(llm_t, 1),
        "env_time_s": round(env_t, 1),
        "traj_time_s": round(traj_t, 1),
        "grading_time_s": round(t.get("reward_calc_time", 0) or 0, 1),
        "patch_chars": len(t.get("output_patch") or ""),
    }


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    csv_out = None
    if "--csv" in sys.argv:
        csv_out = sys.argv[sys.argv.index("--csv") + 1]
    if not args:
        w = os.environ.get("RESULTS_DIR", "/scratch/moham98/swemaster/results")
        args = [f"{w}/runA/runA.jsonl", f"{w}/runB/runB.jsonl"]

    rows = {}
    for f in args:
        if not os.path.exists(f):
            continue
        for line in open(f):
            line = line.strip()
            if not line:
                continue
            try:
                t = json.loads(line)
            except json.JSONDecodeError:
                continue
            m = per_instance(t)
            rows[m["instance_id"]] = m  # dedupe by instance (last wins)

    rows = list(rows.values())
    if not rows:
        print("no results found")
        return

    csv_out = csv_out or "/scratch/moham98/swemaster/results/metrics.csv"
    with open(csv_out, "w", newline="") as fh:
        wr = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
        wr.writeheader()
        wr.writerows(sorted(rows, key=lambda r: r["instance_id"]))

    n = len(rows)
    solved = sum(r["resolved"] for r in rows)

    def agg(key):
        vals = [r[key] for r in rows]
        return sum(vals), st.mean(vals), st.median(vals), max(vals)

    print(f"=== metrics over {n} instances  ({csv_out}) ===")
    print(f"resolved            : {solved}/{n}  ({100*solved/n:.1f}%)")
    print()
    print(f"{'metric':22s} {'total':>12s} {'mean':>10s} {'median':>10s} {'max':>10s}")
    for key in ["num_steps", "completion_tokens", "prompt_tokens",
                "peak_context_tokens", "llm_time_s", "env_time_s",
                "traj_time_s", "grading_time_s"]:
        tot, mean, med, mx = agg(key)
        print(f"{key:22s} {tot:>12,.0f} {mean:>10,.0f} {med:>10,.0f} {mx:>10,.0f}")
    from collections import Counter
    print("\nexit reasons:", dict(Counter(r["exit_reason"] for r in rows)))
    # solved vs unsolved avg steps (does solving correlate with fewer steps?)
    sv = [r["num_steps"] for r in rows if r["resolved"]]
    un = [r["num_steps"] for r in rows if not r["resolved"]]
    if sv:
        print(f"avg steps  solved={st.mean(sv):.0f}  unsolved={st.mean(un):.0f}")


if __name__ == "__main__":
    main()
